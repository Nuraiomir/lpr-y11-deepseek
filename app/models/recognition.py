"""
Что сервис отвечает на кадр.

Поля те же, что отдавал предыдущий сервер на POST /frame, и в том же смысле.
Это сделано сознательно: страница съёмки и оффлайновые прогоны уже написаны
под эти имена, и переименование ради красоты сломало бы их без всякой пользы.
Изменился только адрес.

Главное разделение, которое эти поля держат:

  plate / confirmed   номер прочитан и подтверждён голосованием;
  vehicle             машина найдена в базе.

Это две разные вещи. Номер, которого нет в базе, это успешное распознавание,
и клиент должен сказать именно это: «номер распознан, машина в базе не
найдена». Ответ от базы приходит отдельным запросом (GET /api/v1/vehicle), и
полей о машине в ответе на кадр нет нарочно, чтобы их нельзя было спутать.
"""
from __future__ import annotations

from pydantic import BaseModel, Field


class RecognizeResponse(BaseModel):
    ok: bool = Field(True, description="Кадр обработан. К содержанию ответа не относится")
    plate: str = Field(
        "",
        description="Подтверждённый номер или пустая строка. Непустое значение "
                    "означает, что голосование сошлось, а не что машина есть в базе",
        examples=["322BDM02"],
    )
    confirmed: bool = Field(
        False, description="То же, что непустой plate. Оставлено отдельным полем, "
                           "чтобы клиент не проверял строку на пустоту")
    changed: bool = Field(
        False, description="На этом кадре подтверждён другой номер, чем до него. "
                           "Клиенту это сигнал сбросить показанные данные и "
                           "запросить машину заново")
    # Без указания типа элементов нарочно: четыре координаты целые, пятым
    # идёт уверенность, дробная. Если объявить list[float], координаты уедут
    # в ответ как 200.0 вместо 200, и это изменит форму, под которую написан
    # клиент, ради чистоты описания.
    bbox: list | None = Field(
        None, description="Рамка номера в пикселях кадра: [x1, y1, x2, y2, уверенность]. "
                          "None, если номера на кадре не нашли")
    confidence: float = Field(
        0.0, description="Уверенность детектора в рамке. Это про «здесь номер», "
                         "а не про прочитанные символы")
    # None, а не 0.0 и не пустая строка: OCR на этом кадре мог не запускаться
    # вовсе, и это не то же, что «прочитал с нулевой уверенностью». Поля
    # приходят из распознавателя как есть, подменять None на ноль значило бы
    # придумать чтение, которого не было.
    ocr_confidence: float | None = Field(
        None, description="Уверенность распознавателя в символах последнего чтения. "
                          "None, если OCR на этом кадре не запускался")
    plate_type: str | None = Field(
        None, description="normal однострочный номер, square двухстрочный, "
                          "None если OCR на этом кадре не запускался")
    raw_text: str | None = Field(
        None, description="Что распознаватель прочитал до нормализации и голосования. "
                          "Нужно для разбора ошибок, показывать пользователю не следует")
    session_id: str
    processing_time_ms: float
    frame_size: list[int] = Field(description="[ширина, высота] присланного кадра")
    ocr_variant_mode: str
    profile: dict | None = Field(
        None, description="Разбивка времени по этапам. Появляется только при profile=1")


class ErrorResponse(BaseModel):
    ok: bool = False
    error: str
    error_code: str = Field(
        description="Машиночитаемая причина: bad_request, unauthorized, "
                    "decode_failed, payload_too_large, engine_unavailable, "
                    "internal_error")
