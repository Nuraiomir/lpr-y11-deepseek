#!/bin/sh
# Запуск сервиса в контейнере.
#
# Делает три вещи и не делает ничего лишнего: проверяет, что модель на месте,
# печатает параметры запуска и отдаёт процесс uvicorn.
#
# set -e: любая неудавшаяся команда останавливает запуск. Без этого ошибка в
# проверке прошла бы незамеченной, и сервис поднялся бы в непонятном виде.
set -e

PORT="${PORT:-8080}"
WORKERS="${UVICORN_WORKERS:-1}"
MODEL_PATH="${MODEL_PATH:-/app/model/best11n_512.onnx}"

echo "сервис:   ${APP_NAME:-example-service} ${APP_VERSION:-0.1.0}"
echo "окружение: ${ENVIRONMENT:-dev}"
echo "модель:   ${MODEL_PATH}"
echo "сборка:   ${LPR_ENGINE:-in_process}, устройство ${LPR_DEVICE:-cpu}"
echo "потоков:  ${ORT_THREADS:-1}"
echo "порт:     ${PORT}, процессов uvicorn: ${WORKERS}"

# Модель проверяется здесь, при запуске, а не при первом кадре. Если её нет,
# об этом надо узнать из журнала запуска, а не из таймаута у сотрудника.
# Сервис при этом не падает: он поднимется и честно ответит 503 на
# /health/ready с причиной, а кластер не станет гонять его по кругу
# перезапусков (см. app/main.py).
if [ ! -e "${MODEL_PATH}" ]; then
    echo "ВНИМАНИЕ: модели нет по пути ${MODEL_PATH}."
    echo "          Сервис поднимется, но /health/ready ответит 503."
    echo "          Проверьте MODEL_PATH и монтирование каталога модели."
fi

# Один процесс uvicorn, не несколько. Причина не в простоте: каждый процесс
# грузит обе модели в свою память, и при квоте в одно ядро второй процесс не
# ускоряет ответы, а только удваивает память. Масштабируется это числом
# реплик, где память считает кластер, а не числом процессов внутри пода.
#
# exec: uvicorn занимает место этого скрипта и получает сигналы напрямую,
# иначе SIGTERM при остановке пода дошёл бы до sh, а не до сервиса, и
# завершение шло бы по таймауту.
exec uvicorn app.main:app \
    --host 0.0.0.0 \
    --port "${PORT}" \
    --workers "${WORKERS}" \
    --no-access-log \
    --timeout-keep-alive 10
